  function hash(str) {
    let h = 0;
    const s = String(str || '');
    for (let i = 0; i < s.length; i++) h = ((h << 5) - h + s.charCodeAt(i)) | 0;
    return Math.abs(h);
  }

  function recipeText(recipe, ingredients, tags) {
    const ingText = (ingredients || []).map(i => (typeof i === 'string' ? i : (i && i.name) || '')).join(' ');
    return [recipe && recipe.title, recipe && recipe.description, ingText, (tags || []).join(' ')]
      .join(' ')
      .toLowerCase();
  }

  const general = TIPS.filter(t => t.kw.length === 0);

  /** A tip that fits the recipe (falls back to a general tip). */
  function tipForRecipe(recipe, ingredients, tags) {
    const text = recipeText(recipe, ingredients, tags);
    const title = String((recipe && recipe.title) || '').toLowerCase();
    const hits = (t, s) => t.kw.some(k => s.includes(k.toLowerCase()));
    // Tips that match the dish name are the most relevant; then anything in the recipe.
    const titleMatches = TIPS.filter(t => hits(t, title));
    const matches = titleMatches.length ? titleMatches : TIPS.filter(t => hits(t, text));
    const pool = matches.length ? matches : general;
    const key = (recipe && (recipe.id || recipe.recipeId || recipe.title)) || text;
    return pool[hash(key) % pool.length].text;
  }

  function dayKey(date) {
    const d = date || new Date();
    return `${d.getFullYear()}-${d.getMonth() + 1}-${d.getDate()}`;
  }

  function dayNumber(date) {
    const d = date || new Date();
    return Math.floor(Date.UTC(d.getFullYear(), d.getMonth(), d.getDate()) / 86400000);
  }

  /** One fact per calendar day. */
  function factOfTheDay(date) {
    return FACTS[dayNumber(date) % FACTS.length];
  }

  /** A general tip, stable for the day. `slot` (0, 1, 2…) gives each screen a different tip. */
  function generalTip(slot, date) {
    return general[(dayNumber(date) + (Number(slot) || 0) * 3) % general.length].text;
  }

  window.CookingTips = { tipForRecipe, factOfTheDay, generalTip, dayKey, TIPS, FACTS };
